import { describe, expect, it } from "vitest";
import {
  compareVersions,
  formatVersion,
  lockWithVersion,
  nextPatch,
  parseVersion,
  tagOf,
  type Version,
  withWorkspaceVersion,
  workspaceVersion,
} from "../release/version";

function version(text: string): Version {
  const parsed = parseVersion(text);
  if (!parsed) throw new Error(`${text} should parse`);
  return parsed;
}

describe("parseVersion", () => {
  it("reads a release and a pre-release", () => {
    expect(parseVersion("1.2.3")).toEqual({ major: 1, minor: 2, patch: 3, prerelease: [] });
    expect(parseVersion(" 0.2.0-alpha.1 ")).toEqual({ major: 0, minor: 2, patch: 0, prerelease: ["alpha", "1"] });
    expect(parseVersion("1.0.0-x-y.0a")?.prerelease).toEqual(["x-y", "0a"]);
  });

  it("refuses what is not x.y.z with an optional pre-release", () => {
    for (const text of [
      "",
      "1",
      "1.2",
      "v1.2.3",
      "1.2.3.4",
      "01.2.3",
      "1.2.3-",
      "1.2.3-01",
      "1.2.3-a..b",
      "1.2.3+build",
    ]) {
      expect(parseVersion(text), text).toBeNull();
    }
  });

  it("writes a version back as it was read", () => {
    for (const text of ["0.1.0", "10.20.30", "0.2.0-alpha.1", "1.0.0-rc"]) {
      expect(formatVersion(version(text))).toBe(text);
    }
  });
});

describe("compareVersions", () => {
  it("orders by SemVer's precedence", () => {
    const ordered = [
      "0.1.0",
      "0.1.1",
      "0.2.0-alpha",
      "0.2.0-alpha.1",
      "0.2.0-alpha.2",
      "0.2.0-alpha.10",
      "0.2.0-alpha.beta",
      "0.2.0-beta",
      "0.2.0-rc.1",
      "0.2.0",
      "0.10.0",
      "1.0.0",
    ];
    for (let index = 1; index < ordered.length; index++) {
      const before = version(ordered[index - 1]!);
      const after = version(ordered[index]!);
      expect(compareVersions(before, after), `${ordered[index - 1]} < ${ordered[index]}`).toBeLessThan(0);
      expect(compareVersions(after, before)).toBeGreaterThan(0);
    }
    expect(compareVersions(version("0.2.0-rc.1"), version("0.2.0-rc.1"))).toBe(0);
  });
});

describe("nextPatch", () => {
  it("is the next patch of a release, and a pre-release's own release", () => {
    expect(formatVersion(nextPatch(version("0.1.0")))).toBe("0.1.1");
    expect(formatVersion(nextPatch(version("1.9.9")))).toBe("1.9.10");
    expect(formatVersion(nextPatch(version("0.2.0-alpha.1")))).toBe("0.2.0");
  });
});

describe("tagOf", () => {
  it("puts a v before the version", () => {
    expect(tagOf("0.1.0")).toBe("v0.1.0");
  });
});

const cargoToml = `[workspace]
members = ["crates/*"]

[workspace.package]
edition = "2024"
version = "0.1.0"
license = "CC0-1.0"

[workspace.dependencies]
serde = { version = "1.0.219" }
`;

describe("the workspace's version in Cargo.toml", () => {
  it("is read from [workspace.package] only", () => {
    expect(workspaceVersion(cargoToml)).toBe("0.1.0");
    expect(workspaceVersion('[package]\nversion = "1.0.0"\n')).toBeNull();
    expect(workspaceVersion('[workspace.package]\nedition = "2024"\n\n[other]\nversion = "1.0.0"\n')).toBeNull();
  });

  it("is rewritten without touching anything else", () => {
    const rewritten = withWorkspaceVersion(cargoToml, "0.1.1");
    expect(rewritten).toBe(cargoToml.replace('version = "0.1.0"', 'version = "0.1.1"'));
    expect(rewritten).toContain('serde = { version = "1.0.219" }');
    expect(withWorkspaceVersion("[workspace]\n", "0.1.1")).toBeNull();
  });
});

const cargoLock = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "a-registry-crate"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "our_app"
version = "0.1.0"
dependencies = [
 "our-plugin",
]

[[package]]
name = "our-plugin"
version = "0.1.0"
dependencies = [
 "a-registry-crate",
]
`;

describe("lockWithVersion", () => {
  it("moves the workspace's own crates to the version, and nothing else", () => {
    const expected = lockWithVersion(cargoLock, "0.2.0-alpha.1");
    expect(expected.match(/version = "0\.2\.0-alpha\.1"/g)).toHaveLength(2);
    expect(expected).toContain('name = "a-registry-crate"\nversion = "0.1.0"');
    expect(expected).toContain("version = 4\n");
    expect(expected.replaceAll("0.2.0-alpha.1", "0.1.0")).toBe(cargoLock);
  });
});
